#!/usr/bin/env python3
"""Rasterise Natural Earth's land polygons into the 64x32 mask the world map app draws.

The panel is 2:1 and so is an equirectangular world, so one pixel is 5.625 degrees square.
Each pixel is sampled on a 6x6 grid and counts as land when more than a third of the samples
fall on land, which keeps Great Britain, Japan and New Zealand without inflating the coasts.

The source is public domain (naturalearthdata.com), and the generated header is checked in,
the same arrangement bdf_to_header.py has for the font. To regenerate:

    curl -fsSO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
    python3 -I tools/landmask_to_header.py ne_110m_land.geojson src/gfx/world_map_data.h

It prints the mask as text, which is the quickest way to judge a change by eye.
"""

import json
import sys
from pathlib import Path

WIDTH = 64
HEIGHT = 32
SAMPLES = 6
THRESHOLD = 1 / 3


def rings(geojson):
    for feature in geojson["features"]:
        geometry = feature["geometry"]
        polygons = (
            [geometry["coordinates"]]
            if geometry["type"] == "Polygon"
            else geometry["coordinates"]
        )
        for polygon in polygons:
            yield from polygon


def inside(lon, lat, all_rings):
    """Even-odd over every ring: holes cancel themselves without being told apart."""
    crossings = 0
    for ring in all_rings:
        for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
            if (y1 > lat) != (y2 > lat) and lon < x1 + (lat - y1) * (x2 - x1) / (y2 - y1):
                crossings += 1
    return crossings % 2 == 1


def rasterise(all_rings):
    mask = []
    for row in range(HEIGHT):
        line = []
        for column in range(WIDTH):
            hits = 0
            for sy in range(SAMPLES):
                lat = 90 - (row + (sy + 0.5) / SAMPLES) * 180 / HEIGHT
                for sx in range(SAMPLES):
                    lon = -180 + (column + (sx + 0.5) / SAMPLES) * 360 / WIDTH
                    hits += inside(lon, lat, all_rings)
            line.append(hits / SAMPLES**2 > THRESHOLD)
        mask.append(line)
    return mask


def header(mask):
    data = []
    for line in mask:
        for start in range(0, WIDTH, 8):
            byte = 0
            for bit, land in enumerate(line[start : start + 8]):
                byte |= land << (7 - bit)
            data.append(byte)

    rows = ",\n".join(
        "    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 8]) for i in range(0, len(data), 8)
    )
    return f"""// Copyright (C) 2026 RobBotzz
//
// This program is free software; you can redistribute it and/or modify it under
// the terms of the GNU General Public License, version 2, as published by the
// Free Software Foundation. See LICENSE for details.
//
// GENERATED by tools/landmask_to_header.py from Natural Earth's 1:110m land
// polygons (public domain). Do not edit by hand.

#pragma once

#include <array>
#include <cstdint>

namespace matrixos::world
{{

constexpr int kMapWidth = {WIDTH};
constexpr int kMapHeight = {HEIGHT};

/// One bit per pixel, row-major, most significant bit first. Row 0 is 90 N to
/// 84.375 N, column 0 is 180 W to 174.375 W.
constexpr std::array<std::uint8_t, {len(data)}> kLandMask = {{{{
{rows},
}}}};

}} // namespace matrixos::world
"""


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    all_rings = list(rings(json.loads(Path(sys.argv[1]).read_text())))
    mask = rasterise(all_rings)
    for line in mask:
        print("".join("#" if land else "." for land in line))
    Path(sys.argv[2]).write_text(header(mask))


if __name__ == "__main__":
    main()
